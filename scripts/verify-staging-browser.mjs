import { chromium } from '@playwright/test';
import { readFileSync, mkdirSync } from 'node:fs';
import assert from 'node:assert/strict';
const fixture = JSON.parse(readFileSync('supabase/.temp/staging-verification.json','utf8'));
const config = JSON.parse(readFileSync('supabase/.temp/staging-public.json','utf8'));
assert.equal(config.url,'https://vcgqxlbhsbilxlkratbw.supabase.co');
const browser = await chromium.launch({headless:true});
mkdirSync('test-results/staging',{recursive:true});
try {
for (const [name,width,height] of [['desktop',1440,1100],['mobile',390,844]]) {
  const context = await browser.newContext({viewport:{width,height},acceptDownloads:true});
  // Fail closed if a browser request ever targets a non-staging Supabase project.
  await context.route('https://*.supabase.co/**',route=>new URL(route.request().url()).origin===config.url ? route.continue() : route.abort());
  const page = await context.newPage();
  page.setDefaultTimeout(30000);
  page.setDefaultNavigationTimeout(120000);
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto('http://localhost:3002/hiring');
  await page.getByLabel('Email',{exact:true}).fill(fixture.accounts.alice.email);
  await page.getByLabel('Password',{exact:true}).fill(fixture.accounts.alice.password);
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await page.getByRole('heading',{name:fixture.job.title,exact:true}).waitFor();
  await page.locator('.hiring-record').filter({has:page.getByRole('heading',{name:fixture.job.title,exact:true})}).getByRole('link',{name:'View listing',exact:true}).click();
  await page.getByRole('heading',{name:fixture.job.title,exact:true}).waitFor();
  await page.getByRole('link',{name:'Estimate take-home pay for this role'}).click();
  assert.equal(await page.getByLabel('Monthly gross',{exact:false}).inputValue(),'200,000');
  await page.getByRole('button',{name:'Calculate take-home pay',exact:true}).click();
  await page.getByRole('heading',{name:'Your estimated take-home'}).waitFor();
  await page.getByRole('button',{name:'Check my payslip with these figures'}).click();
  assert.equal(await page.getByLabel('Monthly gross',{exact:false}).inputValue(),'200,000');
  assert.equal(await page.getByLabel('PAYE deducted',{exact:false}).inputValue(),'');
  assert(!page.url().includes('200000'));
  await page.goto('http://localhost:3002/salaries');
  await page.getByRole('heading',{name:fixture.salary_role.toLowerCase(),exact:true}).waitFor();
  await page.getByRole('button',{name:'Share my salary',exact:false}).click();
  await page.getByLabel('Month this salary applied').fill(new Date().toISOString().slice(0,7));
  await page.getByLabel('Job title',{exact:true}).fill('QA Browser Report '+name);
  await page.getByLabel('Industry',{exact:true}).fill('Technology');
  await page.getByLabel('Work location',{exact:true}).fill('Lagos');
  await page.getByLabel('Years of experience').selectOption('3-5');
  await page.getByLabel('Company size').selectOption('1-10');
  await page.locator('input[name=gross]').fill('200000');
  await page.locator('select[name=reliability]').selectOption('on-time');
  for (const check of await page.locator('#community-share input[type=checkbox]').all()) await check.check();
  await page.locator('#community-share button[type=submit]').click();
  await page.getByText(/Your report is awaiting review/).waitFor();
  await page.goto('http://localhost:3002/payroll?view=team');
  await page.getByRole('heading',{name:'Your team',exact:true}).waitFor();
  await page.getByText('Test Employee',{exact:true}).waitFor();
  await page.getByRole('button',{name:/^History/}).click();
  await page.getByRole('heading',{name:'Payroll history'}).waitFor();
  await page.getByText('Superseded',{exact:true}).waitFor();
  await page.getByText('Finalised',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Payroll & payslips',exact:true}).click();
  const pdfPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:'Download draft payslip for Test Employee'}).click();
  const pdf=await pdfPromise;
  const path=await pdf.path(); assert.equal(readFileSync(path).subarray(0,4).toString(),'%PDF');
  const csvPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:'Download draft CSV'}).click();
  const csv=await csvPromise;
  assert(readFileSync(await csv.path(),'utf8').includes('Test Employee'));
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Horizontal overflow');
  await page.screenshot({path:`test-results/staging/${name}-payroll.png`,fullPage:true});
  assert.deepEqual(errors,[]);
  console.log(`PASS ${name}: employer sign-in, hiring -> published job -> calculator -> payslip check, dated community submission, payroll history, PDF and CSV`);
  await context.close();
}
} finally { await browser.close(); }
