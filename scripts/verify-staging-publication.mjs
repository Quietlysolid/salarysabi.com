import { chromium, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const fixture=JSON.parse(readFileSync('supabase/.temp/staging-verification.json','utf8'));
const config=JSON.parse(readFileSync('supabase/.temp/staging-public.json','utf8'));
assert.equal(config.url,'https://vcgqxlbhsbilxlkratbw.supabase.co');
const origin=process.env.STAGING_APP_ORIGIN||'http://localhost:3002';
assert(['http://localhost:3001','http://localhost:3002'].includes(origin));
const browser=await chromium.launch();
try {
  const context=await browser.newContext();
  await context.route('https://*.supabase.co/**',r=>new URL(r.request().url()).origin===config.url?r.continue():r.abort());
  const page=await context.newPage();
  page.setDefaultTimeout(30000);page.setDefaultNavigationTimeout(120000);
  await page.goto(origin+'/hiring');
  await page.getByLabel('Email',{exact:true}).fill(fixture.accounts.alice.email);
  await page.getByLabel('Password',{exact:true}).fill(fixture.accounts.alice.password);
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await page.getByRole('heading',{name:fixture.job.title,exact:true}).waitFor();
  await page.goto(origin+'/post-a-job');
  await page.getByRole('button',{name:'Next: Salary details',exact:true}).click();
  await expect(page.locator('input[name=title]')).toHaveAttribute('aria-invalid','true');
  const title='TEST ONLY browser publication '+Date.now();
  await page.locator('input[name=title]').fill(title);
  await page.locator('input[name=company_name]').fill('SalarySabi staging QA');
  await page.locator('input[name=location]').fill('Lagos');
  await page.getByRole('button',{name:'Next: Salary details',exact:true}).click();
  await page.locator('input[name=salary_min]').fill('250000');
  await page.locator('input[name=salary_max]').fill('300000');
  await page.getByRole('button',{name:'Next: Application details'}).click();
  await page.locator('input[name=expires_at]').fill(new Date(Date.now()+30*86400000).toISOString().slice(0,10));
  await page.locator('input[name=application_url]').fill('https://example.com/staging-test-only');
  await page.locator('input[name=contact_email]').fill(fixture.accounts.alice.email);
  await page.locator('textarea[name=description]').fill('TEST ONLY. This is a staging-only browser verification of job submission and moderation. It is not a real vacancy and must not be copied into production.');
  await page.locator('input[name=no_candidate_fees_confirmed]').check();
  // Respect the form's existing 1.5s anti-bot threshold on optimized pages.
  await page.waitForFunction(()=>performance.now()>=1600);
  await page.getByRole('button',{name:'Submit job for review'}).click();
  await page.getByRole('heading',{name:'Job submitted for review'}).waitFor().catch(async error=>{
    console.error('Submission status:',await page.locator('.form-message').allTextContents());
    throw error;
  });
  await page.getByRole('navigation',{name:'Employer next steps'}).getByRole('link',{name:'Manage my listings'}).click();
  await page.waitForURL('**/hiring');
  const record=page.locator('.hiring-record').filter({has:page.getByRole('heading',{name:title,exact:true})});
  await expect(record).toContainText('In review');
  await page.reload();
  await expect(record).toContainText('In review');
  const adminContext=await browser.newContext();
  await adminContext.route('https://*.supabase.co/**',r=>new URL(r.request().url()).origin===config.url?r.continue():r.abort());
  const admin=await adminContext.newPage();
  admin.setDefaultTimeout(30000);admin.setDefaultNavigationTimeout(120000);
  await admin.goto(origin+'/admin');
  await admin.getByLabel('Email',{exact:true}).fill(fixture.accounts.admin.email);
  await admin.getByLabel('Password',{exact:true}).fill(fixture.accounts.admin.password);
  await admin.getByRole('button',{name:'Sign in securely'}).click();
  await admin.locator('#admin-review-queue button').filter({hasText:title}).click();
  await admin.getByRole('heading',{name:title,exact:true}).waitFor();
  await expect(admin.getByRole('button',{name:'Complete 3 checks to publish'})).toBeDisabled();
  // Deliberately synthetic evidence on the isolated staging project only.
  await admin.getByRole('checkbox',{name:/Application is active/}).check();
  await admin.getByRole('checkbox',{name:/Salary matches the source/}).check();
  await admin.getByRole('checkbox',{name:/Source confidence is acceptable/}).check();
  await admin.getByRole('button',{name:'Approve verified job',exact:true}).click();
  await expect(admin.getByRole('heading',{name:title,exact:true})).toHaveCount(0);
  await page.reload();
  await expect(record).toContainText('Live');
  await record.getByRole('link',{name:'View listing'}).click();
  await page.waitForURL('**/jobs/**');
  await page.getByRole('heading',{name:title,exact:true}).waitFor();
  const publicUrl=page.url();
  const guest=await browser.newPage();
  await guest.goto(publicUrl);
  await guest.getByRole('heading',{name:title,exact:true}).waitFor();
  console.log('PASS real browser submission -> persisted employer record -> admin checks -> publication -> anonymous job page');
} finally { await browser.close(); }
